// Operador condicional ternário (condição, se verdadeiro, se falso):

let age = 22;

/*
  definindo condição: Se age for maior ou igual a 18, então eu quero que apareça "você pode dirigir", caso contrário (age menor que 18) a outra mensagem que deve aparecerm é: "você não pode dirigir".
*/

// coondição (age >= 18), se verdadeiro ("Você pode dirigir"), se falso ("Você não pode dirigir"):
console.log(age >= 18 ? "Você pode dirigir": "Você não pode dirigir.");