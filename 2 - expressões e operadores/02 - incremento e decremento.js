// Incremento e Decremento: 

// dessa forma incrementamos +1 na variável number:
let number = 10;
number++; // incrementa

// incrementa após, por isso não vemos no console
console.log("INCREMENTO: ", number++); // saída: 11
console.log(number); // saída: 12

// Decremento vai funcionar da mesma forma, repare que ambos (-- e ++) podem vir antes ou depois da variável.
console.log("DECREMENTO: ", --number); // saída: 11

// Incrementar grandes valores.
number += 10;
console.log(number); // saída: 21

// DEcrementar grandes valores.
number -= 1;
console.log(number); // saída: 20

