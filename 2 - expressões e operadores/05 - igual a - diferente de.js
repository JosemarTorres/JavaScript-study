// Igual a - Diferente de: 

let one = 1;
let two = 2;

// igual a (==):
console.log("IGUAL A: ", one == two); // saída: false

// esse operador considera o conteúdo e não o tipo dele. 
console.log("IGUAL A: ", one == "1"); // saída: true  


// diferente de (!=):
console.log("DIFERENTE DE: ", one != two); // saída: true 

// esse operador considera o conteúdo e não o tipo dele.
console.log("DIFERENTE DE: ", one != "1"); // saída: false 






