// Estritamente igual a & diferente de (tipo e valor -> "===" & "!==");

let one = 1;
let two = 2;

// estritamente igual a:
console.log("ESTRITAMENTE IGUAL A: ", one === "1"); // saída: false

console.log("ESTRITAMENTE IGUAL A: ", one === 1); // saída: true

// estritamente diferente de:
console.log("ESTRITAMENTE DIFERENTE DE: ", one !== "1"); // saída: true

console.log("ESTRITAMENTE DIFERENTE DE: ", one !== 1); // saída: false

