/*
  Maior que: >
  Menor que: <
  Igual: =
*/

let balance = 500;
let payment = 120;

// maior que: >
console.log(balance > payment); // saída: true 

// menor que: >
console.log(balance < payment); // saída: false 

// maior ou igual a: >=
balance = 120;
console.log(balance >= payment); // saída: true 

// menor ou igual a: <=
balance = 120;
console.log(balance <= payment); // saída: true 
