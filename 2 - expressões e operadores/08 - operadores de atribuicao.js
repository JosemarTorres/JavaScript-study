// Operadores de atribuição:

// atribuição:
value = 1; 
console.log("ATRIBUIÇÃO: ", value); // saída: 1

// incremento:
value += 1; 
console.log("INCREMENTO: ", value); // saída: 2

// decremento:
value -= 1; 
console.log("DECREMENTO: ", value); // saída: 1

// multiplicação:
value *= 6; 
console.log("MULTIPLICAÇÃO: ", value); // saída: 6

// DIVISÃO:
value /= 2; 
console.log("DIVISÃO: ", value); // saída: 3

// RESTO DA DIVISÃO:
value %= 2; 
console.log("RESTO DA DIVISÃO: ", value); // saída: 1

// EXPONENCIAÇÃO:
value **= 2; 
console.log("EXPONENCIAÇÃO: ", value); // saída: 1
